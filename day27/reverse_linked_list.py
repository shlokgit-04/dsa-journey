# LC 206 Reverse Linked List (Easy)
# Iterative pointer reversal: prev/curr walk, next saved each step.
class ListNode:
    def __init__(self, val=0, next=None):
        self.val = val
        self.next = next

def reverse_list(head):
    prev = None
    curr = head
    while curr:
        nxt = curr.next
        curr.next = prev
        prev = curr
        curr = nxt
    return prev
