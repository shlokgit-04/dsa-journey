"""LC 125 Valid Palindrome (Easy, Two Pointers).

Keep only alphanumeric characters, lowercase them, then check the
string reads the same both ways with an inward-walking two-pointer scan.
"""
class Solution:
    def isPalindrome(self, s: str) -> bool:
        left, right = 0, len(s) - 1
        while left < right:
            while left < right and not s[left].isalnum():
                left += 1
            while left < right and not s[right].isalnum():
                right -= 1
            if s[left].lower() != s[right].lower():
                return False
            left += 1
            right -= 1
        return True
